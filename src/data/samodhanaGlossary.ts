export function getTaleSamodhana(tale: JatakaTale): SamodhanaMapping[] {
  if (tale.samodhana && tale.samodhana.length > 0) {
    return tale.samodhana;
  }
  return (
    CURATED_SAMODHANA[tale.id] || [
      {
        pastCharacter: `ตัวละครเอกในเรื่อง ${tale.title}`,
        presentIdentity: 'พระสัมมาสัมพุทธเจ้า (สมัยบำเพ็ญพระโพธิสัตว์)',
      },
      {
        pastCharacter: 'กัลยาณมิตรและผู้ร่วมบำเพ็ญธรรมในเรื่อง',
        presentIdentity: 'พระอริยสาวกและพุทธบริษัทในสมัยพุทธกาล',
      },
    ]
  );
}

